/**
 * Returns the deterministic daily quote based on the current date,
 * ensuring the quote automatically changes every calendar day.
 */
export function getDailyQuote(date: Date = new Date()): CeleMotivationalQuote {
  // Compute day of the year
  const startOfYear = new Date(date.getFullYear(), 0, 1);
  const diff = date.getTime() - startOfYear.getTime();
  const oneDay = 1000 * 60 * 60 * 24;
  const dayOfYear = Math.floor(diff / oneDay);
  
  // Deterministic daily index mapped to 0..119
  const index = Math.abs((dayOfYear + (date.getFullYear() - 2026) * 365) % CELE_MOTIVATIONAL_QUOTES.length);
  return CELE_MOTIVATIONAL_QUOTES[index];
}
